// Real browser smoke against the isolated synthetic backend, never the live run.
import assert from 'node:assert/strict'
const modulePath = process.env.LOOPLAB_PLAYWRIGHT_MODULE
if (!modulePath) throw new Error('Set LOOPLAB_PLAYWRIGHT_MODULE to an installed playwright/index.mjs')
const { chromium } = await import(modulePath)
const url = process.env.LOOPLAB_BROWSER_FIXTURE_URL || 'http://127.0.0.1:18974'
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${url}/#/run/browser-campaign`)
  await page.getByRole('button', { name: 'Report', exact: true }).click()
  await page.getByText('Research map', { exact: true }).click()
  await page.getByText('Does context improve the result?', { exact: true }).first().waitFor()
  await page.getByText('Context comparison', { exact: true }).waitFor()
  await page.getByText('Context study overview', { exact: true }).waitFor()
  await page.getByRole('heading', { name: 'Project metric profile: Vision profile' }).waitFor()
  await page.getByText('Edit project metric profile', { exact: true }).click()
  await page.getByLabel('Denominator').waitFor()
  await page.getByRole('button', { name: 'Show paired comparison' }).click()
  await page.getByText('control → treatment · IoU · heldout', { exact: true }).waitFor()
  await page.getByText('Control: 0.5', { exact: false }).waitFor()
  await page.getByRole('img', { name: /IoU, heldout/ }).waitFor()
  await page.getByText('Related report versions', { exact: false }).locator('button').first().click()
  await page.getByText('Earlier detailed evidence.', { exact: true }).waitFor()
  const earlier = page.locator('.report-version-list li').filter({ hasText: 'Earlier result' })
  await earlier.getByRole('button', { name: 'View report' }).click()
  await page.getByText('Earlier detailed evidence.', { exact: true }).waitFor()
  await earlier.locator('input[type=checkbox]').check()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export selected reports' }).click()])
  assert.match(download.suggestedFilename(), /research\.md$/)
  const { readFile } = await import('node:fs/promises')
  assert.match(await readFile(await download.path(), 'utf8'), /Earlier detailed evidence\./)
  await page.getByRole('button', { name: 'Open question board' }).first().click()
  await page.getByRole('button', { name: 'Research', exact: true }).click()
  await page.getByText('Does context improve the result?', { exact: true }).first().waitFor()
  await page.getByRole('button', { name: 'Report', exact: true }).click()
  await page.getByText('Later detailed evidence.', { exact: true }).waitFor()
  await page.getByRole('combobox', { name: 'Interface and generated text language' }).selectOption('ru')
  await page.getByText('Карта исследования', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS real Chromium: direction → registered comparison → paired result → full historical report → board → current report → Russian UI')
} finally { await browser.close() }
