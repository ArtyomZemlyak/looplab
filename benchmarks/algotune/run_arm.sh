#!/bin/bash
# ДРАЙВЕР ПАРНОГО АРМА: N батчей по четыре пробы, два плеча, скрещенные полосы.
#
#   ARM=B1 bash run_arm.sh            # прочитает PREREGISTERED-B1.txt и покажет, что потратит
#   ARM=B1 ARM_GO=1 bash run_arm.sh   # запустит
#
# ЗАЧЕМ ОН ВООБЩЕ. До 18.09 такого файла не было: §137 и арм по капу проб гонялись руками. Двенадцать
# батчей B1 — это 48 проб и $48, и каждая из них должна получить своё плечо, свою полосу и свою
# предрегистрацию. Рука, которая делает это 48 раз, ошибётся; и ошибётся она молча, потому что
# перепутанное плечо выглядит как обычная проба. Драйвер существует ради ЗАПИСИ пары, а не ради
# удобства: `arm.jsonl` пишется ДО запуска пробы, одна строка на пробу, и анализ читает её, а не
# догадывается по имени каталога.
#
# ПОЛОСЫ СКРЕЩЕНЫ, И ЭТО §266. Над 37 пробами старого арма 17 из 18 пролеченных прошли по первым
# двум полосам, а 18 из 19 контрольных — по последним двум. Перестановочный тест §190 переставляет
# МЕТКИ внутри батча, и это законно ровно тогда, когда четыре пробы батча взаимозаменяемы; про
# полосы этого никто не показывал. Измерение линейкой по всем четырём полосам дало +4.5 % в пользу
# пролеченных при p = 0.016 — и при повторе порядок полос перемешался (шесть сидений, знаковый тест
# p = 0.34). То есть смещения не доказано, но и исключить его нечем: полоса 22-32,70-80 за шесть
# сидений самая низкая (0.9127 против 0.9448).
#
# Поэтому отображение МЕНЯЕТСЯ каждый батч по чётности:
#
#   нечётный батч:  TREAT -> A, B      control -> C, D
#   чётный батч:    TREAT -> C, D      control -> A, B
#
# На двенадцати батчах каждое плечо получает каждую полосу ровно шесть раз. Если полосы
# взаимозаменяемы — не потеряно ничего; если нет — конфаунд стал оцениваемым вместо неизмеримого.
#
# ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ: он не считает и не печатает НИ ОДНОГО исхода. Обе предрегистрации
# кончаются строкой «READ ONCE, at N complete batches. No interim look.» Драйвер, печатающий
# p-value между батчами, — это и есть промежуточный взгляд, и никакая дисциплина оператора его потом
# не развидит.
set -u

HERE="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
ARM="${ARM:-}"
TASK="${TASK:-}"
BUDGET="${ARM_BUDGET:-1.00}"
OUT_ROOT="${ARM_OUT_ROOT:-${BENCH_ROOT:-/var/tmp/looplab-bench}/arms}"
METER="${METER_BASE:-http://127.0.0.1:8801}"
MODEL="${LOOPLAB_LLM_MODEL:-}"

# ЧЕТЫРЕ ПОЛОСЫ ЭТОЙ КОРОБКИ. Одиннадцать ядер плюс их гипертред-близнецы: 22 CPU, `auto` даёт
# 22 воркера, ключ эталона `__w22x1r3` — режим, в котором измерен весь корпус. Полоса из ОДНОГО
# диапазона ключует `__w11x1r3`, кэша под него нет, и `run_probe.sh` откажет (§431.1).
LANE_A="0-10,48-58"; LANE_B="11-21,59-69"; LANE_C="22-32,70-80"; LANE_D="33-43,81-91"

die() { echo "ОТКАЗ: $*" >&2; exit 2; }

[ -n "$ARM" ] || die "не задан ARM (например ARM=B1)"
[ -n "$MODEL" ] || die "не задана LOOPLAB_LLM_MODEL — источник benchmarks/box-jhub-l40s.sh"

PRE="$HERE/PREREGISTERED-$ARM.txt"
[ -s "$PRE" ] || die "нет предрегистрации $PRE. Арм без неё не начинается (docs/56 §187)"

# РАЗМЕР И ЛЕЧЕНИЕ БЕРУТСЯ ИЗ ПРЕДРЕГИСТРАЦИИ, А НЕ ИЗ КОМАНДНОЙ СТРОКИ. Число батчей — это
# зарегистрированный размер; аргумент, которым его можно переопределить, — это ручка, которой
# однажды подкрутят размер под уже увиденные данные. Оператор, которому нужен другой размер,
# правит предрегистрацию и оставляет след в git.
BATCHES=$(sed -n 's/^batches:[[:space:]]*\([0-9][0-9]*\).*/\1/p' "$PRE" | head -1)
[ -n "$BATCHES" ] || die "$PRE не называет batches:"
SETTING=$(sed -n 's/.*PROBE_LOOPLAB_SETTINGS="--set \([^"]*\)".*/\1/p' "$PRE" | head -1)
[ -n "$SETTING" ] || die "$PRE не называет форму запуска PROBE_LOOPLAB_SETTINGS=\"--set <поле>=<значение>\""
[ -n "$TASK" ] || TASK=$(sed -n 's/^TASK[[:space:]]*\([a-z0-9_]*\).*/\1/p' "$PRE" | head -1)
[ -n "$TASK" ] || die "$PRE не называет TASK и он не задан переменной"

PROBES=$(( BATCHES * 4 ))
TOTAL=$(awk -v n="$PROBES" -v b="$BUDGET" 'BEGIN{printf "%.2f", n*b}')

cat <<INFO
арм:            $ARM
задача:         $TASK
батчей:         $BATCHES  ->  $PROBES проб по \$$BUDGET  =  \$$TOTAL
лечение:        --set $SETTING
контроль:       поставочные настройки
полосы:         нечётный батч TREAT=$LANE_A,$LANE_B  чётный TREAT=$LANE_C,$LANE_D  (§266)
каталог:        $OUT_ROOT/$ARM
предрегистрация: $PRE
INFO

if [ "${ARM_GO:-0}" != "1" ]; then
  echo
  echo "это показ. Запуск: ARM=$ARM ARM_GO=1 bash $0"
  exit 0
fi

mkdir -p "$OUT_ROOT/$ARM" || die "не создать $OUT_ROOT/$ARM"
MANIFEST="$OUT_ROOT/$ARM/arm.jsonl"

# СЛЕПОК ПРЕДРЕГИСТРАЦИИ РЯДОМ С ДАННЫМИ, и он же проверяется на неизменность. Файл в репозитории
# можно поправить между батчем 3 и батчем 9, и git это покажет — но только тому, кто пойдёт смотреть.
# Здесь отказ приходит сам.
SNAP="$OUT_ROOT/$ARM/PREREGISTERED.snapshot.txt"
if [ -s "$SNAP" ]; then
  cmp -s "$SNAP" "$PRE" || die "предрегистрация ИЗМЕНИЛАСЬ с начала арма: $PRE против $SNAP.
  Арм читается один раз, в конце; изменить его условия посередине — это и есть тот самый
  промежуточный взгляд. Либо верни файл, либо начинай новый арм под новым именем."
else
  cp "$PRE" "$SNAP" || die "не записать $SNAP"
fi

say() { echo "[$(date +%H:%M:%S)] $*"; }

for B in $(seq 1 "$BATCHES"); do
  if [ $(( B % 2 )) -eq 1 ]; then
    T1="$LANE_A"; T2="$LANE_B"; C1="$LANE_C"; C2="$LANE_D"
  else
    T1="$LANE_C"; T2="$LANE_D"; C1="$LANE_A"; C2="$LANE_B"
  fi
  say "===== батч $B/$BATCHES ====="
  PIDS=""
  for spec in "t1:treat:$T1" "t2:treat:$T2" "c1:control:$C1" "c2:control:$C2"; do
    SLOT="${spec%%:*}"; REST="${spec#*:}"; COND="${REST%%:*}"; LANE="${REST#*:}"
    LABEL="$ARM-b$(printf '%02d' "$B")-$SLOT-$COND"
    DIR="$OUT_ROOT/$ARM/$LABEL"
    if [ -f "$DIR/INSTRUMENT.txt" ] && grep -q . "$DIR/probe.log" 2>/dev/null \
       && grep -q 'ИТОГ:' "$DIR/probe.log" 2>/dev/null; then
      say "  $LABEL — уже отработала, пропуск"
      continue
    fi
    mkdir -p "$DIR"
    # КАЖДАЯ ПРОБА НЕСЁТ СВОЮ ПРЕДРЕГИСТРАЦИЮ: `run_probe.sh::require_preregistration` ищет её в
    # каталоге ПРОБЫ, и без неё пролеченная проба откажется стартовать (exit 4). Контрольная не
    # обязана, но получает тот же файл — чтобы каталог батча нельзя было прочитать как «у одних
    # есть, у других нет».
    cp "$SNAP" "$DIR/PREREGISTERED.txt"
    # СТРОКА В МАНИФЕСТ ПИШЕТСЯ ДО ЗАПУСКА. Проба, которая упадёт, должна остаться в записи как
    # упавшая проба этого плеча, а не исчезнуть: исчезнувшая пролеченная проба смещает арм ровно
    # настолько, насколько она отличалась.
    printf '{"arm":"%s","batch":%d,"slot":"%s","condition":"%s","lane":"%s","label":"%s","budget":"%s","task":"%s","started":"%s"}\n' \
      "$ARM" "$B" "$SLOT" "$COND" "$LANE" "$LABEL" "$BUDGET" "$TASK" "$(date -Iseconds)" >> "$MANIFEST"
    if [ "$COND" = "treat" ]; then
      PROBE_LOOPLAB_SETTINGS="--set $SETTING" PROBE_OUT_ROOT="$OUT_ROOT/$ARM" \
        setsid nohup bash "$HERE/run_probe.sh" "$MODEL" "$LABEL" "$LANE" "$TASK" "$METER" "$BUDGET" \
        > "$DIR/driver.log" 2>&1 < /dev/null &
    else
      PROBE_OUT_ROOT="$OUT_ROOT/$ARM" \
        setsid nohup bash "$HERE/run_probe.sh" "$MODEL" "$LABEL" "$LANE" "$TASK" "$METER" "$BUDGET" \
        > "$DIR/driver.log" 2>&1 < /dev/null &
    fi
    PIDS="$PIDS $!"
    say "  $LABEL -> полоса $LANE ($COND)"
    sleep 5
  done
  # БАТЧ — ЕДИНИЦА, и следующий не стартует, пока этот не закрыт: `arm_power.py` считает мощность
  # по ПАРНЫМ батчам, а четыре пробы, из которых две доехали в одном состоянии коробки, а две в
  # другом, парными не являются.
  for P in $PIDS; do wait "$P" 2>/dev/null; done
  say "батч $B закрыт"
done

say "арм $ARM: все $BATCHES батчей отработаны. Манифест: $MANIFEST"
echo
echo "Чтение — ОДИН раз, по $SNAP. Этот драйвер не считает исходов намеренно."
