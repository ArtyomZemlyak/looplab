#!/bin/bash
# СТАРОЕ ИМЯ ОДНОЙ И ТОЙ ЖЕ ПРОБЫ. Тело переехало в `run_probe.sh`; здесь остался только вызов.
#   run_model_probe.sh <модель> <короткая-метка> <полоса> [задача] [база-счётчика] [бюджет]
#
# ПОЧЕМУ НЕ ДВА ФАЙЛА. Это были две копии одного скрипта с одинаковыми умолчаниями
# (`edge_expansion`, счётчик на 8802, бюджет $1.00) — и починили только одну. В этой оставалось:
#
#   * `CH=$(ls -t "$OUT/runs/$TASK/run"/nodes/*/solver.py | head -1)` — САМЫЙ СВЕЖИЙ solver.py, а
#     не лучший. На пробе `convex_hull` 27.08 узел 0 имел train-оценку 3.7777, узел 1 — 2.7342, и
#     `ls -t` вернул узел 1, потому что он записан позже (06:00:53 против 04:30:53). На тесте
#     померили его: 2.7829. Настоящий чемпион на тесте не измерялся вообще, и весь день это число
#     докладывалось как результат пробы. `run_probe.sh` зовёт `extract_champion.py --run-dir`,
#     который читает свёртку событий и знает `state.best()` — как кампания;
#   * `cp` ОДНОГО файла вместо `extract_champion.py --all-files`: многофайловый чемпион
#     (`.pyx` + `setup.py`) приезжал на оценку без своих же файлов и не собирался;
#   * не было проверки, что у задачи вообще есть датасет (28.08 в 15:58 проба на
#     `count_connected_components` стартовала, потратила $0.0042 и оценивать было нечем).
#
# А шапка ПОЧИНЕННОГО `run_probe.sh` в строке использования звала именно этот файл — то есть
# оператор, читающий исправленный скрипт, запускал сломанный. Копия, которая расходится, здесь уже
# стоила дня ложных докладов; второй экземпляр правила не заводим, оставляем перенаправление.
#
# ЗНАНИЕ, КОТОРОЕ ЖИЛО В ЭТОЙ ШАПКЕ, — в `run_probe.sh`: почему `edge_expansion`, почему это не
# прямое сравнение с 27.1295, профиль расходов по трём моделям и повадки GLM-5.3-flash.
#
# `exec` — та же защита от правки на ходу, что и обёртка в функцию у `run_probe.sh`, только строже:
# процесс замещается, и оболочке больше нечего дочитывать из этого файла.
# `CDPATH= cd --`: an exported CDPATH makes `cd` ECHO the directory it resolved for any operand
# that does not start with / ./ or .., so `$( )` would capture TWO lines and this exec would die
# 127 on a path nobody can see in the error.
exec bash "$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/run_probe.sh" "$@"
